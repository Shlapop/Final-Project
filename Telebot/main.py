#Стартовое сообщение
@bot.message_handler(commands=["start"])
def send_welcome(message):
    bot.reply_to(message, "👋 Привет! Я твой экологический бот 🌍\n"
                          "Вот что я умею:\n"
                          "/hello — дружеский привет\n"
                          "/fact — интересный факт об экологии (без повторов)\n"
                          "/help_ecology — полезный совет по экологии\n"
                          "/restart — перезапустить список фактов")

#Команда /hello
@bot.message_handler(commands=["hello"])
def send_hello(message):
    bot.reply_to(message, "Привет! 😊 Как дела?")

#Команда /fact — отправляет уникальный факт
@bot.message_handler(commands=["fact"])
def send_fact(message):
    global unused_facts
    if unused_facts:
        fact = random.choice(unused_facts)
        unused_facts.remove(fact)
        bot.reply_to(message, f"📘 Факт: {fact}")
    else:
        bot.reply_to(message, "Все факты были показаны. Напиши /restart, чтобы начать заново.")

#Команда /restart — сбрасывает список фактов
@bot.message_handler(commands=["restart"])
def restart_facts(message):
    global unused_facts
    unused_facts = facts.copy()
    bot.reply_to(message, "Список фактов успешно обновлён! Пиши /fact, чтобы узнать новый.")

#Команда /help_ecology — отправляет случайный совет
@bot.message_handler(commands=["help_ecology"])
def send_help_tip(message):
    tip = random.choice(help_tips)
    bot.reply_to(message, f"♻️ Совет: {tip}")

